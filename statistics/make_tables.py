"""Print Tables III to VI of the paper from statistics/results.json (run compute_statistics.py first).

    python statistics/make_tables.py            # writes statistics/tables.md

As in the paper, differences are computed from the three-decimal values.
A '*' marks a 95% interval that excludes the published value (the PI in Table III) or zero (every CI).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LABEL = {"hs": "HS", "aw": "AW", "tp": "TP", "hs_aw": "HS+AW", "hs_tp": "HS+TP", "tp_aw": "TP+AW",
         "tp_aw_hs": "TP+AW+HS", "ts_or_tp_hs": "TS+OR+TP+HS", "lr": "LR"}
NINE = list(LABEL)
MODEL = {"deepseek-coder-1.3b": "DSC-1.3B", "deepseek-coder-6.7b": "DSC-6.7B", "codellama-7b": "CodeLlama-7B",
         "deepseek-coder-33b": "DSC-33B", "qwen2.5-coder-7b": "Qwen-7B"}
ORIGINAL = list(MODEL)[:4]
PAIRS = [("deepseek-coder-6.7b", "DSC-6.7B -> 1.3B"), ("deepseek-coder-33b", "DSC-33B -> 1.3B"),
         ("qwen2.5-coder-7b", "Qwen-7B -> 1.5B")]


def r3(x):
    return round(x, 3)


def d3(a, b):
    return round(r3(a) - r3(b), 3)


def t3(x):
    return ("-" if x < 0 else "") + f"{abs(x):.3f}"[1:]


def sg(x):
    return ("-" if x < 0 else "+") + f"{abs(x):.3f}"[1:]


def mark(s, significant):
    return s + ("*" if significant else "")


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main():
    res = json.loads((ROOT / "statistics/results.json").read_text(encoding="utf-8"))
    T = res["test_sets"]
    parts = ["# Tables III to VI", "",
             "Generated by statistics/make_tables.py from statistics/results.json. "
             "A cell marked * is significant (see the script's docstring).", ""]

    parts.append("## Table III. RQ1 and RQ2: published (Orig.), reproduced (Repr.), task-disjoint (Disj.)\n")
    for m in ORIGINAL:
        o, t = T[f"original_split_{m}"], T[f"task_disjoint_{m}"]
        rows = []
        for d in NINE:
            q = res["rq1"][m]["detectors"][d]
            mean = q["reproduced"]
            half = q["prediction_interval"][1] - mean
            lo, hi = max(0.0, round(r3(mean) - r3(half), 3)), min(1.0, round(r3(mean) + r3(half), 3))
            assert (lo <= q["published"] <= hi) == q["reproduces"]
            s = res["rq2"][m][d]
            delta, h = d3(t["detectors"][d]["mean"], o["detectors"][d]["mean"]), r3((s["hi"] - s["lo"]) / 2)
            lo2, hi2 = round(delta - h, 3), round(delta + h, 3)
            assert (lo2 <= 0 <= hi2) == (not s["significant"])
            rows.append([LABEL[d], t3(q["published"]), t3(mean), mark(f"[{t3(lo)}, {t3(hi)}]", not q["reproduces"]),
                         t3(t["detectors"][d]["mean"]), mark(f"[{t3(lo2)}, {t3(hi2)}]", s["significant"])])
        rows.append(["Random", t3(res["rq1"][m]["main_minus_baselines"]["Random"]["value"]), t3(o["share_hallucinated"]), "",
                     t3(t["share_hallucinated"]), ""])
        parts += [f"### {MODEL[m]}\n", table(["Features", "Orig.", "Repr.", "95% PI", "Disj.", "95% CI"], rows), ""]
    n_rep = sum(c["reproduces"] for v in res["rq1"].values() for c in v["detectors"].values())
    parts += [f"Published values that reproduce: {n_rep} of 36.", ""]

    settings = [("task_disjoint_qwen2.5-coder-7b", "Mixed Qwen-7B")] + [
        (f"bigcodebench_{m}", f"BigCodeBench {MODEL[m]}") for m in MODEL]
    rows = [[LABEL[d]] + [t3(T[s]["detectors"][d]["mean"]) for s, _ in settings] for d in NINE]
    rows.append(["Random"] + [t3(T[s]["share_hallucinated"]) for s, _ in settings])
    parts += ["## Table IV. RQ3: the nine detectors in the six new settings\n",
              table(["Features"] + [lab for _, lab in settings], rows), ""]

    rows = []
    for bench, prefix in (("Mixed", "task_disjoint"), ("BigCodeBench", "bigcodebench")):
        for m in MODEL:
            s = T[f"{prefix}_{m}"]
            v = {d: s["detectors"][d]["mean"] for d in ("tp", "richtp", "hs_tp", "hs_richtp")}
            cells = [f"{bench} {MODEL[m]}"] + [t3(v[d]) for d in ("tp", "richtp", "hs_tp", "hs_richtp")]
            cells.append(t3(s["share_hallucinated"]))
            for a, b in (("richtp", "tp"), ("hs_tp", "tp"), ("hs_richtp", "richtp")):
                c = s["differences"][f"{a} - {b}"]
                lo, hi = round(c["lo"], 3), round(c["hi"], 3)
                cells.append(mark(f"{sg(d3(v[a], v[b]))} [{sg(lo)}, {sg(hi)}]", not lo <= 0 <= hi))
            change = round(d3(v["hs_richtp"], v["richtp"]) - d3(v["hs_tp"], v["tp"]), 3)
            c = s["differences"]["change in HS gain"]
            lo, hi = round(c["lo"], 3), round(c["hi"], 3)
            cells.append(mark(f"{sg(change)} [{sg(lo)}, {sg(hi)}]", not lo <= 0 <= hi))
            rows.append(cells)
    parts += ["## Table V. RQ4: TP, RichTP, HS+TP, HS+RichTP and their differences\n",
              table(["Setting", "TP", "RichTP", "HS+TP", "HS+RichTP", "Random", "RichTP - TP", "(HS+TP) - TP",
                     "(HS+RichTP) - RichTP", "Change in HS gain"], rows), ""]

    rows = []
    for bench, prefix in (("Mixed", "task_disjoint"), ("BigCodeBench", "bigcodebench")):
        for m, lab in PAIRS:
            s = T[f"{prefix}_{m}"]
            v = {d: s["detectors"][d]["mean"] for d in ("richtp", "hs_richtp", "student", "distilled")}
            cells = [f"{bench} {lab}"] + [t3(v[d]) for d in ("richtp", "hs_richtp", "student", "distilled")]
            cells.append(t3(s["share_hallucinated"]))
            for a, b in (("student", "richtp"), ("hs_richtp", "student"), ("distilled", "student")):
                c = s["differences"][f"{a} - {b}"]
                lo, hi = round(c["lo"], 3), round(c["hi"], 3)
                cells.append(mark(f"{sg(d3(v[a], v[b]))} [{sg(lo)}, {sg(hi)}]", not lo <= 0 <= hi))
            rows.append(cells)
    parts += ["## Table VI. RQ5: the Teacher's RichTP with the hidden states of the Teacher, the Student, or the "
              "distilled Student\n",
              table(["Pair", "RichTP", "Teacher", "Student", "Distilled", "Random", "Student - RichTP",
                     "Teacher - Student", "Distilled - Student"], rows), ""]
    fit = res["rq5_distillation"]
    parts += ["Distillation, validation R^2 of the Student's predictions of the Teacher's hidden states "
              "(base Student, mean of the three distilled runs): " + "; ".join(
                  f"{p}: {v['base_validation_mean_r2']:.3f} -> {v['validation_mean_r2']:.3f} ({sg(v['gain'])})"
                  for p, v in fit.items()), ""]
    out = ROOT / "statistics/tables.md"
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
